int main()
{
	const auto add = Span(kAddSubtitle);
	const auto show = Span(kShowSubtitle);
	constexpr std::uintptr_t addAt = kBase + 0x8CCBB0;
	constexpr std::uintptr_t showAt = kBase + 0x8CD260;

	// The add tests both settings back to back, 0x7F bytes in.
	Expect(FindEitherSettingTest(add, addAt, kGeneral, kDialogue) == 0x7F,
		"finds the add's either-setting test");

	// The same bytes anywhere else point at other memory.
	Expect(FindEitherSettingTest(add, addAt + 0x1000, kGeneral, kDialogue) == kNotFound,
		"the test only matches where the displacements land on the settings");

	// The order matters: Dialogue first is a different test.
	Expect(FindEitherSettingTest(add, addAt, kDialogue, kGeneral) == kNotFound,
		"the settings must be tested in the given order");

	// The display pass reads both settings too, but far apart: it isn't the add.
	Expect(FindEitherSettingTest(show, showAt, kGeneral, kDialogue) == kNotFound,
		"the display pass is not mistaken for the add");

	// Too short to hold two tests.
	Expect(FindEitherSettingTest(add.subspan(0x7F, 10), addAt + 0x7F, kGeneral, kDialogue) == kNotFound,
		"a cut-off test is not found");
	Expect(FindEitherSettingTest(add.subspan(0x7F, 0x10), addAt + 0x7F, kGeneral, kDialogue) == 0,
		"two whole tests are enough");

	// The add's entry: mov r11, rsp; push rbp; push rsi. Exactly five bytes, nothing
	// RIP-relative.
	{
		const auto entry = ReadEntry(add, addAt);
		Expect(entry.kind == Entry::Kind::kCode, "the add's entry can be moved");
		Expect(entry.length == 5, "the add's entry is moved in five bytes");
	}

	// The display pass opens with mov rax, rsp; push rbp; push rsi too.
	{
		const auto entry = ReadEntry(show, showAt);
		Expect(entry.kind == Entry::Kind::kCode && entry.length == 5, "the display pass's entry reads the same");
	}

	// Further into the add: push rdi, then the four REX pushes and sub rsp, 0x70.
	Expect(MovableLength(add, 5) == 1, "push rdi");
	Expect(MovableLength(add, 6) == 2, "push r12");
	Expect(MovableLength(add, 14) == 4, "sub rsp, imm8");
	Expect(MovableLength(add, 18) == 8, "mov [r11-0x80], imm32");
	Expect(MovableLength(add, 26) == 4, "mov [r11+0x18], rbx");

	// movzx and gs: loads are not prologue forms; they are refused, not guessed.
	Expect(MovableLength(add, 30) == 0, "movzx is refused");
	Expect(MovableLength(add, 50) == 0, "a segment-prefixed load is refused");

	// A RIP-relative load must never be moved.
	Expect(MovableLength(add, 43) == 0, "mov r10d, [rip+disp] is refused");
	{
		constexpr std::array<std::uint8_t, 8> ripFirst{ 0x48, 0x8B, 0x05, 0x10, 0x20, 0x30, 0x40, 0x90 };
		Expect(ReadEntry(Span(ripFirst), 0x1000).kind == Entry::Kind::kUnknown,
			"an entry starting with a RIP-relative load is left alone");
	}

	// Common entries elsewhere.
	{
		constexpr std::array<std::uint8_t, 8> saveRbx{ 0x48, 0x89, 0x5C, 0x24, 0x08, 0x57, 0x48, 0x83 };
		const auto entry = ReadEntry(Span(saveRbx), 0x1000);
		Expect(entry.kind == Entry::Kind::kCode && entry.length == 5, "mov [rsp+8], rbx is five bytes");

		constexpr std::array<std::uint8_t, 8> pushes{ 0x40, 0x53, 0x48, 0x83, 0xEC, 0x20, 0x90, 0x90 };
		const auto pushed = ReadEntry(Span(pushes), 0x1000);
		Expect(pushed.kind == Entry::Kind::kCode && pushed.length == 6, "push rbx; sub rsp, 0x20 takes six bytes");

		constexpr std::array<std::uint8_t, 6> tooShort{ 0x40, 0x53, 0x48, 0x83, 0xEC, 0x20 };
		Expect(ReadEntry(Span(tooShort).first(4), 0x1000).kind == Entry::Kind::kUnknown,
			"an instruction cut off by the end of the bytes is refused");
	}

	// Another mod got there first with jmp rel32: follow it.
	{
		constexpr std::array<std::uint8_t, 8> jump{ 0xE9, 0xFB, 0x0F, 0x00, 0x00, 0xCC, 0xCC, 0xCC };
		const auto entry = ReadEntry(Span(jump), 0x10000);
		Expect(entry.kind == Entry::Kind::kJump, "an existing jmp rel32 is recognised");
		Expect(entry.target == 0x10000 + 5 + 0xFFB, "the jump's target is decoded");

		constexpr std::array<std::uint8_t, 8> back{ 0xE9, 0xF6, 0xFF, 0xFF, 0xFF, 0xCC, 0xCC, 0xCC };
		Expect(ReadEntry(Span(back), 0x10000).target == 0x10000 + 5 - 10, "a backward jump is decoded");
	}

	// Or with jmp [rip+disp]: the pointer is read at run time.
	{
		constexpr std::array<std::uint8_t, 14> indirect{ 0xFF, 0x25, 0x00, 0x00, 0x00, 0x00, 1, 2, 3, 4, 5, 6, 7, 8 };
		const auto entry = ReadEntry(Span(indirect), 0x10000);
		Expect(entry.kind == Entry::Kind::kIndirect, "an existing jmp [rip+disp] is recognised");
		Expect(entry.pointer == 0x10006, "the pointer sits right after the jump");
	}

	return EXIT_SUCCESS;
}
